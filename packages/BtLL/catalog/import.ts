/// <reference types="node" />
// Generates GradTrak requirement programs (BtLL) from the Berkeley catalog and
// the overrides in overrides/. Usage: npm run import:catalog
import { writeFileSync } from "node:fs";

import { sanityCheck, toBtLL } from "./btll";
import { CATALOG_ID, catalogCourseCodes, fetchPrograms } from "./coursedog";
import { applyOverrides, readOverride } from "./overrides";

// Catalog names must exactly match a GradTrak major/minor
const PROGRAMS = [
  "25345U", // English major
  "25I071U", // Mathematics minor
  "16I020U", // Structural Engineering minor
  "25179U", // Cognitive Science major
  "16279U", // Aerospace Engineering major
  "25699U", // Political Science major
  "25I072U", // Physics minor
  "04779U", // Environmental Economics and Policy major
  "z5SVnW3RWZv5syG4KuEY", // Ecosystem Management and Forestry major
  "25I034U", // Chinese Language minor
];

interface Output {
  name: string;
  major: string | null;
  minor: string | null;
  code: string;
}

async function main() {
  const programs = await fetchPrograms(PROGRAMS);
  const overrides = programs.map((p) => readOverride(p.id));
  const validCodes = overrides.some(Boolean)
    ? await catalogCourseCodes()
    : new Set<string>();

  const output: Output[] = [];
  const catalogRules: object[] = [];
  programs.forEach((p, i) => {
    const label = `${p.name} (${p.kind})`;
    let rules = p.rules;
    catalogRules.push({
      programGroupId: p.id,
      name: p.name,
      kind: p.kind,
      flags: [...p.flags],
      rules,
    });

    const ov = overrides[i];
    if (ov) {
      rules = applyOverrides(rules, ov, validCodes, label);
      p.flags.push(`override applied (${ov.changes?.length ?? 0} changes)`);
    }
    const code = toBtLL(rules);
    sanityCheck(code, rules, label);

    const name = `${p.name} ${p.kind === "major" ? "Major" : "Minor"} Requirements`;
    output.push({
      name,
      major: p.kind === "major" ? p.name : null,
      minor: p.kind === "minor" ? p.name : null,
      code,
    });
    const placeholders = rules.filter((r) => r.kind === "placeholder").length;
    const converted = rules.length - placeholders;
    const flags = p.flags.length ? ` [${p.flags.join("; ")}]` : "";
    console.log(
      `+ ${name}: ${converted} converted, ${placeholders} placeholders${flags}`
    );
  });

  writeFileSync(
    new URL("./rules.generated.json", import.meta.url),
    JSON.stringify(catalogRules, null, 2) + "\n"
  );
  const file = `// GENERATED by catalog/import.ts from the Berkeley catalog (catalog ${CATALOG_ID}). Do not edit.
// Regenerate with: npm run import:catalog -w @repo/BtLL

export const CATALOG_REQUIREMENTS: {
  name: string;
  major: string | null;
  minor: string | null;
  code: string;
}[] = ${JSON.stringify(output, null, 2)};
`;
  writeFileSync(new URL("./reqs.generated.ts", import.meta.url), file);
  console.log(`\nWrote ${output.length} programs to reqs.generated.ts`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
